type TranslationKey = keyof (typeof T)["en"];

export function useTranslation() {
  const { settings } = useApp();
  const lang: Lang = (settings.language as Lang) || "en";
  const dict = T[lang] as Record<string, string>;
  const t = (key: TranslationKey): string => dict[key] ?? (T.en as Record<string, string>)[key] ?? key;
  return { t, lang };
}
